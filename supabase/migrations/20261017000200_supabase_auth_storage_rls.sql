create or replace function portal.current_user_id()
returns text
language sql
stable
security definer
set search_path = portal, public
as $$
  select id
  from portal.users
  where auth_user_id = auth.uid()
    and deleted = false
  limit 1
$$;

create or replace function portal.has_role(required_role text)
returns boolean
language sql
stable
security definer
set search_path = portal, public
as $$
  select exists (
    select 1
    from portal.user_roles ur
    join portal.roles r on r.id = ur.role_id
    where ur.user_id = portal.current_user_id()
      and ur.deleted = false
      and r.deleted = false
      and r.name = required_role
  )
$$;

create or replace function portal.sync_auth_user()
returns trigger
language plpgsql
security definer
set search_path = portal, public
as $$
declare
  portal_user_id text;
  requested_role text;
  requested_role_id text;
begin
  select id into portal_user_id
  from portal.users
  where lower(email) = lower(new.email)
  limit 1;

  if portal_user_id is null then
    portal_user_id := new.id::text;
    insert into portal.users (
      id, auth_user_id, name, email, phone, status, author
    ) values (
      portal_user_id,
      new.id,
      coalesce(new.raw_user_meta_data ->> 'name', split_part(new.email, '@', 1)),
      new.email,
      new.phone,
      coalesce(new.raw_user_meta_data ->> 'status', 'active'),
      'supabase_auth'
    );
  else
    update portal.users
    set auth_user_id = new.id,
        email = new.email,
        phone = coalesce(new.phone, phone),
        name = coalesce(new.raw_user_meta_data ->> 'name', name),
        updated_at = now()
    where id = portal_user_id;
  end if;

  requested_role := new.raw_app_meta_data ->> 'role';
  if requested_role is not null and requested_role <> '' then
    select id into requested_role_id
    from portal.roles
    where name = requested_role and deleted = false
    limit 1;

    if requested_role_id is null then
      requested_role_id := gen_random_uuid()::text;
      insert into portal.roles (id, name, author)
      values (requested_role_id, requested_role, 'supabase_auth');
    end if;

    if not exists (
      select 1 from portal.user_roles
      where user_id = portal_user_id
        and role_id = requested_role_id
        and deleted = false
    ) then
      insert into portal.user_roles (user_id, role_id, author)
      values (portal_user_id, requested_role_id, 'supabase_auth');
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert or update of email, phone, raw_user_meta_data, raw_app_meta_data
  on auth.users
  for each row execute procedure portal.sync_auth_user();

-- All application tables are accessed through authenticated Edge Functions.
-- Enabling RLS with no broad anon/authenticated policies prevents accidental
-- exposure through PostgREST; the service-role client in Edge Functions bypasses RLS.
do $$
declare
  table_row record;
begin
  for table_row in
    select schemaname, tablename
    from pg_tables
    where schemaname in ('portal', 'ticket', 'inventory')
  loop
    execute format('alter table %I.%I enable row level security', table_row.schemaname, table_row.tablename);
  end loop;
end
$$;

-- storage.objects already has RLS enabled and is owned by supabase_storage_admin.

drop policy if exists "portal file owners can read" on storage.objects;
-- No direct Storage read policy is granted. The API Edge Function performs
-- portal-level authorization and returns a short-lived signed URL.

revoke all on all tables in schema portal from anon, authenticated;
revoke all on all tables in schema ticket from anon, authenticated;
revoke all on all tables in schema inventory from anon, authenticated;
grant usage on schema portal, ticket, inventory to authenticated;
grant execute on function portal.current_user_id() to authenticated;
grant execute on function portal.has_role(text) to authenticated;

-- Edge Functions use the service-role client. BYPASSRLS does not replace
-- ordinary schema/table/sequence privileges on custom schemas.
grant usage on schema portal, ticket, inventory to service_role;
grant all privileges on all tables in schema portal, ticket, inventory to service_role;
grant usage, select on all sequences in schema portal, ticket, inventory to service_role;
alter default privileges in schema portal grant all privileges on tables to service_role;
alter default privileges in schema ticket grant all privileges on tables to service_role;
alter default privileges in schema inventory grant all privileges on tables to service_role;
alter default privileges in schema portal grant usage, select on sequences to service_role;
alter default privileges in schema ticket grant usage, select on sequences to service_role;
alter default privileges in schema inventory grant usage, select on sequences to service_role;
